<template>
    <div class="similarity-evidence">
        <!-- Code comparison panel -->
        <div v-if="showCode" :class="['code-panel', { inset: !bleed }]">
            <div v-if="codeLoading" class="code-loading">Loading code...</div>
            <div v-else-if="codeError" class="code-loading">Couldn't load the code. Try again later.</div>
            <div v-else-if="code" class="code-columns">
                <div v-for="side in code.sides" :key="side.label" class="code-col">
                    <div class="code-col-header">{{ side.label }}</div>
                    <div class="code-body">
                        <div
                            v-for="(line, i) in side.lines"
                            :key="i"
                            :class="['code-line', side.matched.has(i) ? 'match' : '']"
                        >
                            <span class="line-num">{{ i + 1 }}</span>
                            <span v-if="markRenamed && side.matched.has(i)" class="line-text"><template
                                v-for="(piece, k) in splitRenamed(line, side.renamed)" :key="k"><span
                                v-if="piece.renamed" class="renamed">{{ piece.text }}</span><template v-else>{{ piece.text }}</template></template></span>
                            <span v-else class="line-text">{{ line || ' ' }}</span>
                        </div>
                    </div>
                </div>
            </div>
        </div>

        <!-- Model explanation panel — evidence for the trainer, not a verdict -->
        <div v-if="showExplanation" class="ai-expl-panel">
            <div v-if="explLoading" class="code-loading">Loading explanation...</div>
            <div v-else-if="expl" class="ai-expl-body">
                <div class="ai-expl-head">
                    <span class="ai-expl-title">Model explanation</span>
                    <span :class="['confidence-badge', confidenceClass(expl.confidence)]" title="How strongly the model thinks the code was copied">{{ humanize(expl.confidence) }} model confidence</span>
                </div>
                <p class="ai-expl-summary">{{ expl.summary }}</p>
                <ul class="ai-expl-matches">
                    <li v-for="(m, i) in expl.matches" :key="i">{{ m }}</li>
                </ul>
                <p class="ai-expl-disclaimer">Generated by a model. Check the evidence.</p>
            </div>
            <div v-else-if="explPending" class="ai-expl-empty">
                No model explanation available for this pair yet.
            </div>
        </div>
    </div>
</template>

<script setup lang="ts">
// The evidence of one similarity pair: both submissions side by side with the matching
// lines highlighted, and the model's explanation. Used on the exam case file.
// The parent decides which panels are open; each loads the first time it opens.
import { ref, watch } from 'vue'
import api from '../api'
import { humanize } from '../utils/format'
import { confidenceClass } from '../utils/metrics'
import { findMatchedLines, findRenamedNames, splitRenamed } from '../utils/codeCompare'

const props = withDefaults(defineProps<{
    pair: { id: number; submission_1: number; submission_2: number }
    label1: string
    label2: string
    showCode: boolean
    showExplanation: boolean
    bleed?: boolean          // code panel runs to the edges of a 20px-padded card
    markRenamed?: boolean    // underline names that differ between the two files
}>(), { bleed: true, markRenamed: false })

interface Side { label: string; lines: string[]; matched: Set<number>; renamed: Set<string> }
interface PlagiarismExplanation {
    summary: string
    matches: string[]
    confidence: 'low' | 'medium' | 'high'
}

const code = ref<{ sides: Side[] } | null>(null)
const codeLoading = ref(false)
const codeError = ref(false)
const expl = ref<PlagiarismExplanation | null>(null)
const explLoading = ref(false)
const explPending = ref(false)   // explanation not generated yet (or unavailable)

async function loadCode(): Promise<void> {
    if (code.value || codeLoading.value) return
    codeLoading.value = true
    codeError.value = false
    try {
        const [r1, r2] = await Promise.all([
            api.get(`/submissions/${props.pair.submission_1}/`),
            api.get(`/submissions/${props.pair.submission_2}/`),
        ])
        const lines1: string[] = (r1.data.code || '').split('\n')
        const lines2: string[] = (r2.data.code || '').split('\n')
        const { matched1, matched2 } = findMatchedLines(lines1, lines2)
        const { renamed1, renamed2 } = props.markRenamed
            ? findRenamedNames(lines1, lines2)
            : { renamed1: new Set<string>(), renamed2: new Set<string>() }
        code.value = { sides: [
            { label: props.label1, lines: lines1, matched: matched1, renamed: renamed1 },
            { label: props.label2, lines: lines2, matched: matched2, renamed: renamed2 },
        ] }
    } catch {
        codeError.value = true
    } finally {
        codeLoading.value = false
    }
}

async function loadExplanation(): Promise<void> {
    if (expl.value || explLoading.value) return
    explLoading.value = true
    explPending.value = false
    try {
        const res = await api.get(`/ai/plagiarism-explanation/${props.pair.id}/`)
        if (res.data && res.data.summary) expl.value = res.data as PlagiarismExplanation
        else explPending.value = true   // {status: 'pending'}
    } catch {
        explPending.value = true
    } finally {
        explLoading.value = false
    }
}

watch(() => props.showCode, open => { if (open) loadCode() }, { immediate: true })
watch(() => props.showExplanation, open => { if (open) loadExplanation() }, { immediate: true })
</script>

