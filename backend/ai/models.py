from django.db import models  # base module for all Django model fields


class RubricScore(models.Model):
    """GPT-generated qualitative evaluation of a submission.

    Produced async AFTER the test-case result is delivered to the student — this
    never sits on the sub-10s result path. One row per submission.
    """
    submission = models.OneToOneField(
        'submissions.Submission',
        on_delete=models.CASCADE,
        related_name='rubric_score',  # submission.rubric_score
    )

    # Four dimensions, each scored 0-2 with a one-sentence justification.
    correctness_score = models.PositiveSmallIntegerField()          # how well it passes the tests
    correctness_note = models.TextField()
    code_quality_score = models.PositiveSmallIntegerField()         # readability, naming, structure
    code_quality_note = models.TextField()
    approach_score = models.PositiveSmallIntegerField()             # optimality / reasoning of the algorithm
    approach_note = models.TextField()
    edge_case_score = models.PositiveSmallIntegerField()            # boundary-condition handling
    edge_case_note = models.TextField()

    overall_feedback = models.TextField()                          # 2-3 constructive sentences
    model_used = models.CharField(max_length=60, blank=True)       # which GPT model produced this
    created_at = models.DateTimeField(auto_now_add=True)

    @property
    def total_score(self):
        """Sum of the four dimensions, 0-8."""
        return (
            self.correctness_score + self.code_quality_score
            + self.approach_score + self.edge_case_score
        )

    def __str__(self):
        return f"RubricScore(sub={self.submission_id}, total={self.total_score}/8)"


class AIHint(models.Model):
    """GPT-generated Socratic hint for a FAILED submission.

    Generated async after the failed result is delivered. One row per submission;
    stored so it does not regenerate on page refresh. Shown only on demand
    (student clicks "Show Hint").
    """
    submission = models.OneToOneField(
        'submissions.Submission',
        on_delete=models.CASCADE,
        related_name='ai_hint',  # submission.ai_hint
    )
    hint = models.TextField()                                  # 1-3 sentence Socratic nudge
    model_used = models.CharField(max_length=60, blank=True)   # which GPT model produced this
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"AIHint(sub={self.submission_id})"


class PlagiarismExplanation(models.Model):
    """GPT-generated natural-language explanation of why a pair was flagged.

    Generated async at exam close, alongside the existing Layer 2 TF-IDF pass,
    only for pairs flagged above the similarity threshold. It is evidence for the
    trainer's audit trail — the trainer still makes the final call.
    """
    CONFIDENCE_CHOICES = [('low', 'Low'), ('medium', 'Medium'), ('high', 'High')]

    flag = models.OneToOneField(
        'plagiarism.PlagiarismFlag',
        on_delete=models.CASCADE,
        related_name='ai_explanation',  # flag.ai_explanation
    )
    summary = models.TextField()                                  # one sentence: why suspicious
    matches = models.JSONField(default=list)                      # 2-3 concrete observations
    confidence = models.CharField(max_length=10, choices=CONFIDENCE_CHOICES)
    model_used = models.CharField(max_length=60, blank=True)      # which GPT model produced this
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"PlagiarismExplanation(flag={self.flag_id}, conf={self.confidence})"


class ExamSummary(models.Model):
    """GPT-generated summary of how one student did across a whole exam.

    Aggregates that student's per-submission rubric scores and pass/fail outcomes
    for the exam into a short narrative. One row per (student, exam); generated on
    demand the first time the student views it.
    """
    student = models.ForeignKey(
        'accounts.User', on_delete=models.CASCADE, related_name='exam_summaries',
    )
    exam = models.ForeignKey('exams.Exam', on_delete=models.CASCADE, related_name='ai_summaries')
    summary = models.TextField()                                  # 3-4 sentence overview
    model_used = models.CharField(max_length=60, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        unique_together = ('student', 'exam')

    def __str__(self):
        return f"ExamSummary(student={self.student_id}, exam={self.exam_id})"


class WeeklyRecommendation(models.Model):
    """Weekly study advice for one student, written from all of their exams together.

    Generated by Celery beat every Monday morning (IST). One row per (student, week);
    if a week's call fails, the page keeps showing the last good row.
    """
    student = models.ForeignKey(
        'accounts.User', on_delete=models.CASCADE, related_name='weekly_recommendations',
    )
    week_start = models.DateField()                               # Monday (IST) of the week it was written for
    headline = models.TextField()                                 # one sentence
    cards = models.JSONField(default=list)                        # [{kind: keep|work|next, text, evidence}]
    input_digest = models.CharField(max_length=64)                # sha256 of the numbers the model saw
    model_used = models.CharField(max_length=60, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        unique_together = ('student', 'week_start')
        ordering = ['-week_start']

    def __str__(self):
        return f"WeeklyRecommendation(student={self.student_id}, week={self.week_start})"
